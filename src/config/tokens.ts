import type { Address } from 'viem'

export type ItemCategory =
  | 'plant'
  | 'fish'
  | 'crystal'
  | 'stone'
  | 'rune'
  | 'pet-egg'
  | 'pet-treat'
  | 'consumable'
  | 'misc'

export interface TokenInfo {
  name: string
  symbol: string
  address: Address
  decimals: number
  category: ItemCategory
  /** Filename on CDN (with extension), or full URL if starts with http */
  imageFile: string
  /** ERC-1155 token ID (default 0 for ERC-20 tokens) */
  tokenId?: bigint
  /** Whether this is an ERC-20 token (default true) */
  isERC20?: boolean
}

const CDN_BASE = 'https://defi-kingdoms.b-cdn.net/art-assets/items'

export function getItemImageUrl(file: string): string {
  if (file.startsWith('http') || file.startsWith('/')) return file
  return `${CDN_BASE}/${file}`
}

