export interface TokenWithSlug extends TokenInfo {
  /** Registry key used for URLs and lookups */
  slug: string
}

/** Get all tokens as an array with their registry key as `slug` */
export function getAllTokens(): TokenWithSlug[] {
  return Object.entries(TOKENS).map(([slug, token]) => ({ ...token, slug }))
}

/** Get tokens filtered by category */
export function getTokensByCategory(category: ItemCategory): TokenWithSlug[] {
  return getAllTokens().filter((t) => t.category === category)
}

/** Find token by address (case-insensitive) */
export function findTokenByAddress(address: string): TokenInfo | undefined {
  return getAllTokens().find((t) => t.address.toLowerCase() === address.toLowerCase())
}
